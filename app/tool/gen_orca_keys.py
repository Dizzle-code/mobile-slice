#!/usr/bin/env python3
"""Writes test/engine/orca_keys.txt from OrcaSlicer's PrintConfig.cpp.

Line format: key<TAB>type<TAB>enum values (comma separated)<TAB>default expression.
Usage (WSL): python3 app/tool/gen_orca_keys.py <PrintConfig.cpp> app/test/engine/orca_keys.txt
"""
import re
import sys

source = open(sys.argv[1], encoding="utf-8").read()
add = re.compile(r'(?:(\w+)\s*=\s*)?def\s*=\s*this->add(?:_nullable)?\("([a-z0-9_]+)",\s*(co\w+)\)')
entries = {}
aliases = {}
current = None
for line in source.splitlines():
    match = add.search(line)
    if match:
        alias, key, kind = match.groups()
        current = {"type": kind, "enums": [], "default": "", "copy": None}
        entries[key] = current
        if alias:
            aliases[alias] = key
        continue
    if "this->add" in line:
        current = None
    if current is None:
        continue
    value = re.search(r'def->enum_values\.(?:push_back|emplace_back)\("([^"]*)"\)', line)
    if value:
        current["enums"].append(value.group(1))
    copy = re.search(r'def->enum_values\s*=\s*(\w+)->enum_values', line)
    if copy:
        current["copy"] = copy.group(1)
    default = re.search(r'def->set_default_value\((.*)\);', line)
    if default:
        current["default"] = default.group(1).strip()
# Keys declared in a loop that copies existing options under a prefix (e.g. filament_retraction_length).
derived = re.compile(r'for \(const char \*opt_key : \{(.*?)\}\) \{\s*auto it_opt = options\.find\(opt_key\);'
                     r'.*?this->add(?:_nullable)?\(std::string\("(\w+)"\) \+ opt_key', re.S)
for block, prefix in derived.findall(source):
    for base in re.findall(r'"([a-z0-9_]+)"', block):
        entries[prefix + base] = dict(entries[base], default="(copied from " + base + ")", copy=entries[base]["copy"])
for key, entry in entries.items():
    if entry["copy"]:
        entry["enums"] = entries[aliases[entry["copy"]]]["enums"]
with open(sys.argv[2], "w", encoding="utf-8", newline="\n") as out:
    out.write("# Generated by app/tool/gen_orca_keys.py from the pinned engine's PrintConfig.cpp. Do not edit.\n")
    for key in sorted(entries):
        entry = entries[key]
        out.write(f'{key}\t{entry["type"]}\t{",".join(entry["enums"])}\t{entry["default"]}\n')
print(len(entries), "keys")
